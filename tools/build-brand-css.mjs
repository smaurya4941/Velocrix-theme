const hexRe = /#([0-9a-fA-F]{6})\b/g, rgbRe = /rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/g;
const map = s => s.replace(hexRe, (m, h) => HEX[h.toUpperCase()] ? '#' + HEX[h.toUpperCase()] : m)
                  .replace(rgbRe, (m, a, b, c) => { const k = `${a},${b},${c}`; return RGB[k] ? m.replace(k, RGB[k]).replace(/\s/g, '') : m; });
const hits = s => map(s) !== s;

// tiny CSS walker: returns blocks {prelude, body, children}
function parse(src) {
  const out = []; let i = 0;
  while (i < src.length) {
    const open = src.indexOf('{', i); if (open < 0) break;
    const prelude = src.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < src.length && depth) { if (src[j] === '{') depth++; else if (src[j] === '}') depth--; j++; }
    const body = src.slice(open + 1, j - 1);
    out.push({ prelude, body }); i = j;
  }
  return out;
}
let n = 0;
function emit(blocks) {
  let s = '';
  for (const b of blocks) {
    if (/^@media|^@supports/.test(b.prelude)) { const inner = emit(parse(b.body)); if (inner) s += `${b.prelude}{\n${inner}}\n`; continue; }
    if (/^@keyframes/.test(b.prelude)) { if (hits(b.body)) { s += `${b.prelude}{${map(b.body)}}\n`; n++; } continue; }
    if (/^@/.test(b.prelude)) continue;
    const all = b.body.split(/;(?![^(]*\))/).map(x => x.trim()).filter(Boolean);
    const decls = all.filter(hits).map(map);
    // a re-emitted background shorthand resets clip/size/position: repeat the rule's own longhands after it
    if (decls.some(x => /^background\s*:/.test(x)))
      all.filter(x => !hits(x) && /^((-webkit-)?background-(clip|size|position|repeat|origin|attachment)|color|-webkit-text-fill-color)\s*:/.test(x)).forEach(x => decls.push(x));
    if (decls.length) { s += `${b.prelude}{${decls.join(';')}}\n`; n++; }
  }
  return s;
}
const gen = emit(parse(css));
const manual = readFileSync(path.join(ROOT, 'tools/brand-manual.css'), 'utf8');
