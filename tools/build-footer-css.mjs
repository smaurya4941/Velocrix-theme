// Builds assets/landing/css/site-footer.css: the classic footer's rules from assets/css/main.css, scoped to #vxFoot,
// so the shared footer (template-parts/site-footer.php) looks identical on the animated pages.
// Run after changing footer styles in assets/css/main.css:   node tools/build-footer-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const css = readFileSync(path.join(ROOT, 'assets/css/main.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

// selectors that belong to the footer (or that it depends on)
const KEEP = /\.site-footer|\.foot-|\.news-|\.nl-msg|\.social|\.soc-pending|\.round-btn|\.container\b|\.hp\b|\.copy\b|\.copy-assoc|\.brand\b|\.brand-|^(a|ul|ol|li|img|h3|h4|button|input)(\b|:|$)|^\*/;
const SKIP = /\.(stat-card|prog-img|fac|vm-card|programs|hero|page-hero|cta-band|section|partners|page-main|dark|reg-|connect-card|cc-name)\b|\.site-header|\.nav|:root|^body|^html/;

function parse(src) {
  const out = []; let i = 0;
  while (i < src.length) {
    const open = src.indexOf('{', i); if (open < 0) break;
    const prelude = src.slice(i, open).trim(); let d = 1, j = open + 1;
    while (j < src.length && d) { if (src[j] === '{') d++; else if (src[j] === '}') d--; j++; }
    out.push({ prelude, body: src.slice(open + 1, j - 1) }); i = j;
  }
  return out;
}
const scope = sel => {
  sel = sel.trim();
  if (sel.startsWith('.site-footer')) return '#vxFoot' + sel;              // .site-footer .x -> #vxFoot.site-footer .x
  if (/^(a|ul|ol|li|img|h3|h4|button|input)(\b|:|$)/.test(sel) || sel.startsWith('*')) return '#vxFoot ' + sel;
  return '#vxFoot ' + sel;
};
function emit(blocks) {
  let s = '';
  for (const b of blocks) {
    if (/^@media/.test(b.prelude)) { const inner = emit(parse(b.body)); if (inner) s += `${b.prelude}{\n${inner}}\n`; continue; }
    if (/^@/.test(b.prelude)) continue;
    const sels = b.prelude.split(/,(?![^(]*\))/).map(x => x.trim()).filter(x => KEEP.test(x) && !SKIP.test(x));
    if (!sels.length) continue;
    s += sels.map(scope).join(',') + '{' + b.body.trim() + '}\n';
  }
  return s;
}
const out = `/* GENERATED by tools/build-footer-css.mjs from assets/css/main.css. Do not edit by hand; edit main.css and re-run. */
/* Undo the animated design's styles inside the footer, then apply the classic footer rules (all scoped to #vxFoot). */
#vxFoot,#vxFoot :not(svg,svg *),#vxFoot :not(svg,svg *)::before,#vxFoot :not(svg,svg *)::after{all:revert;box-sizing:border-box}
/* (SVG icons are left alone: reverting them would drop their fill/stroke attributes) */
#vxFoot{--lime:#B7E600;--ink:#0b0b0d;--ink2:#16181d;--font:'Public Sans',system-ui,-apple-system,'Segoe UI',Roboto,sans-serif;--maxw:1280px;--gut:24px;--r:28px;--r-sm:18px;
  --bg:var(--ink);--fg:#fff;--muted:#b6b8bf;--card:var(--ink2);--bd:rgba(255,255,255,.14);--limeink:var(--lime);
  display:block;font:400 17px/1.65 var(--font);-webkit-font-smoothing:antialiased;position:relative;z-index:1}
#vxFoot svg{display:inline-block;vertical-align:middle}
@media (max-width:640px){#vxFoot{--gut:18px;--r:22px;font-size:16px}}
${emit(parse(css))}`;
writeFileSync(path.join(ROOT, 'assets/landing/css/site-footer.css'), out);
console.log('site-footer.css', out.length, 'bytes');
